import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const source = readFileSync(new URL('src/passive-webui.mjs', root), 'utf8').replace('export function', 'function');
const start = '/* PASSIVE_UI_START */', end = '/* PASSIVE_UI_END */';
const file = new URL('dist/webui.js', root);
let ui = readFileSync(file, 'utf8');
const marker = '\nexport default {';
if (!ui.includes(marker)) throw Error('Missing panel export');
const startAt = ui.includes(start) ? ui.indexOf(start) : ui.indexOf(marker);
const tailAt = ui.includes(end) ? ui.indexOf(end) + end.length : startAt;
ui = ui.slice(0, startAt).trimEnd() + `\n\n${start}\n${source.trim()}\n${end}\n\n` + ui.slice(tailAt).trimStart();
const registered = /(?:\btokens|['"]tokens['"])\s*:\s*makePassivePanel/;
if (!registered.test(ui)) ui = ui.replace("'deep-checkup': makeDeepCheckupPanel(),", "'deep-checkup': makeDeepCheckupPanel(),\n    'tokens': makePassivePanel('tokens'),\n    'memory-coverage': makePassivePanel('memory'),\n    'context-fit': makePassivePanel('context'),");
if (!registered.test(ui)) throw Error('Panel registration failed');
writeFileSync(file, ui);
const cssFile = new URL('dist/webui.css', root); let css = readFileSync(cssFile, 'utf8');
const cssStart = '/* PASSIVE_STYLE_START */', cssEnd = '/* PASSIVE_STYLE_END */';
const cssAt = css.includes(cssStart) ? css.indexOf(cssStart) : css.length;
const cssTail = css.includes(cssEnd) ? css.indexOf(cssEnd) + cssEnd.length : css.includes('/* GROUPED_STYLE_START */') ? css.indexOf('/* GROUPED_STYLE_START */') : css.length;
writeFileSync(cssFile, css.slice(0, cssAt).trimEnd() + `\n\n${cssStart}\n` + readFileSync(new URL('src/passive-webui.css', root), 'utf8').trim() + `\n${cssEnd}\n\n` + css.slice(cssTail).trimStart());
console.log('Synchronized Token, memory coverage and context fit panels.');
